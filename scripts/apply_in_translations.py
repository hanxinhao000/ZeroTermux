def replace_strings(xml: str, mapping: dict[str, str]) -> tuple[str, int]:
    count = 0

    def repl(m: re.Match[str]) -> str:
        nonlocal count
        name = m.group(1)
        attrs = m.group(2)
        if name not in mapping:
            return m.group(0)
        count += 1
        return f'<string name="{name}"{attrs}>{mapping[name]}</string>'

    out = re.sub(
        r'<string name="([^"]+)"([^>]*)>.*?</string>',
        repl,
        xml,
        flags=re.S,
    )
    return out, count


def main() -> None:
    strings = ROOT / "app/src/main/res/values-in/strings.xml"
    xml, n = replace_strings(strings.read_text(encoding="utf-8"), T)
    strings.write_text(xml, encoding="utf-8")
    print(f"strings.xml: {n} replacements")

    ai = ROOT / "app/src/main/res/values-in/zt_ai_strings.xml"
    xml, n = replace_strings(ai.read_text(encoding="utf-8"), AI)
